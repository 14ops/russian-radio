"""Builds data/dict.js, the tap-a-word dictionary, from the OpenRussian data.

Usage:  python3 tools/build_dict.py <folder with the OpenRussian CSV files>
        (get them with: git clone https://github.com/Badestrand/russian-dictionary)

Keeps the most frequent words of each kind, every word the course uses, and every
pronoun or small word that has an English meaning. Forms keep their slot order, so the
app can say "accusative singular of ры́ба". Stress is an apostrophe after the vowel.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import openrussian as oru  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'data', 'dict.js')
COURSE = os.path.join(HERE, '..', 'data', 'course.js')
LIMIT = {'n': 5000, 'v': 3000, 'a': 2500, 'o': 6000}
DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'
EXTRA = os.path.join(HERE, 'dict_extra.txt')


def short_en(en):
    senses = [s.strip() for s in re.split(r'[,;]', en) if s.strip()]
    out = ''
    for s in senses[:4]:
        nxt = (out + ', ' if out else '') + s
        if len(nxt) > 70:
            break
        out = nxt
    return out or en[:70]


def pack(word, form):
    """Shared-prefix code: one base-36 digit for the shared length, then the rest of the form."""
    n = 0
    while n < min(len(word), len(form), 35) and word[n] == form[n]:
        n += 1
    return DIGITS[n] + form[n:]


def extras():
    rows = []
    if not os.path.exists(EXTRA):
        return rows
    for line in open(EXTRA, encoding='utf-8'):
        line = line.split('#')[0].strip()
        if not line:
            continue
        word, rest = [x.strip() for x in line.split('=', 1)]
        parts = [x.strip() for x in rest.split('|')]
        en, pos = parts[0], parts[1] if len(parts) > 1 else 'o'
        forms = [f.strip() for f in parts[2].split(',')] if len(parts) > 2 and parts[2] else []
        rows.append([word, en, pos, '|'.join(pack(word, f) for f in forms)])
    return rows


def course_words():
    if not os.path.exists(COURSE):
        return set()
    text = open(COURSE, encoding='utf-8').read()
    return {oru.key(t) for t in re.findall(r'[А-Яа-яЁё́]+', text)}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    entries, index = oru.load(sys.argv[1])
    need = course_words()
    keep, seen = [], set()
    for e in entries:
        if not e.en.strip():
            continue
        in_course = any(oru.key(f) in need for fs in [[e.accented]] + list(e.forms.values()) for f in fs)
        if e.rank >= LIMIT[e.pos] and not in_course:
            continue
        sig = (e.pos, e.accented, e.en)
        if sig in seen:
            continue
        seen.add(sig)
        keep.append(e)
    keep.sort(key=lambda e: (e.rank, 'novao'.index(e.pos)))
    rows = []
    for e in keep:
        slots = oru.SLOTS[e.pos]
        forms = '|'.join(','.join(pack(e.accented, f) for f in e.forms.get(s, [])) for s in slots).rstrip('|')
        rows.append([e.accented, short_en(e.en), e.pos + e.info, forms])
    extra = extras()
    rows = extra + rows
    known = set()
    for r in rows:
        known.add(oru.key(r[0]))
        for part in r[3].split('|'):
            for f in part.split(','):
                if f:
                    known.add(oru.key(r[0][:DIGITS.index(f[0])] + f[1:]))
    known |= {k for w in known if '-' in w for k in w.split('-')}
    missing = sorted(w for w in need if w not in known and oru.vowel_count(w) > 0)
    dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'))  # noqa: E731
    head = ('/* Povtori FM tap-a-word dictionary: %d words with their forms.\n'
            '   Data: OpenRussian (https://en.openrussian.org), licensed CC BY-SA 4.0, see LICENSES/openrussian-CC-BY-SA-4.0.txt.\n'
            '   Generated by tools/build_dict.py. Stress is an apostrophe after the vowel.\n'
            '   Entry: [word, English, part of speech + info, forms]. Forms run in slot order, joined by |, variants by commas.\n'
            '   Each form is a base-36 digit, the length it shares with the word, then the rest: "ры\'ба" + "4ы" = "ры\'бы". */\n') % len(rows)
    body = 'window.POVTORI_DICT={v:1,slots:%s,e:[\n%s\n]};\n' % (
        dump({k: v for k, v in oru.SLOTS.items() if v}), ',\n'.join(dump(r) for r in rows))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(head + body)
    size = os.path.getsize(OUT)
    by_pos = {}
    for r in rows:
        by_pos[r[2][0]] = by_pos.get(r[2][0], 0) + 1
    print('wrote %s: %d words (%s), %.2f MB' % (os.path.relpath(OUT), len(rows), ', '.join('%s %d' % kv for kv in sorted(by_pos.items())), size / 1e6))
    print('course words the dictionary does not know (%d): %s' % (len(missing), ' '.join(missing)))


if __name__ == '__main__':
    main()
